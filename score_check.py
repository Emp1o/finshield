from rag import retrieve_scored

questions = [
    "Мне позвонили из банка и просят назвать код из СМС. Что делать?",
    "Что такое безопасный счёт?",
    "Как распознать фишинговое письмо?",
    "Сколько 2 умножить на 2?",
    "Какая погода завтра в Москве?",
    "Как приготовить борщ?",
    "Мне сейчас звонят из службы безопасности и просят продиктовать код",
]

for q in questions:
    ranked = retrieve_scored(q)
    print(f"{ranked[0][1]:.3f}  {q}")